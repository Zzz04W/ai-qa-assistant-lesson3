def write_normalized():
    path = os.path.join(BASE, "02_规范问答集.csv")
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(["qid", "question", "answer", "source_rows", "note"])
        w.writerows(NORMALIZED)
    return path


def write_kb():
    items = []
    for qid, question, answer, rows, _ in NORMALIZED:
        if qid in ("q18", "q19"):
            continue
        items.append({
            "id": qid,
            "question": question,
            "aliases": ALIASES[qid],
            "answer": answer,
            "tags": TAGS[qid],
            "source": f"{qid} + 原始语料行号 {rows}",
            "scope": SCOPE[qid],
            "updated": "课程日期占位（2026-11-23 制作）",
        })
    path = os.path.join(BASE, "03_知识库.json")
    with open(path, "w", encoding="utf-8") as f:
        json.dump({"note": "answer 逐字取自 02_规范问答集.csv；source 记录 qid 与原始语料行号", "items": items},
                  f, ensure_ascii=False, indent=2)
        f.write("\n")
    return path


